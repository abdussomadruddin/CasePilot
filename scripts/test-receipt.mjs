import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import { PDFDocument } from "pdf-lib";
const source = await readFile("src/lib/receipt.ts", "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace('import("pdf-lib")', `import("${pathToFileURL(resolve("node_modules/pdf-lib/cjs/index.js"))}")`);
const { exampleReceipt, receiptTotal, ringgitWords, receiptFilename, buildReceipt } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const data = exampleReceipt();
assert.equal(receiptTotal(data), 2500);
assert.equal(receiptTotal({ ...data, cash: "0.10", cheque: "0.20" }), 2500.30);
assert.equal(receiptTotal({ ...data, totalOverride: "12.30" }), 12.30);
assert.equal(ringgitWords(2500), "TWO THOUSAND FIVE HUNDRED ONLY");
assert.equal(ringgitWords(12.3), "TWELVE AND THIRTY SEN ONLY");
assert.equal(ringgitWords(0), "ZERO ONLY");
assert.equal(ringgitWords(1000000), "ONE MILLION ONLY");
assert.equal(receiptFilename(data), "RECEIPT_LOKMAN_HAKIM_BIN_NORAZHAR_0009_18-09-2026.pdf");
const result = await buildReceipt(await readFile("assets/receipt-template.pdf"), data);
const doc = await PDFDocument.load(result);
assert.equal(doc.getPageCount(), 1);
assert.ok(doc.getPage(0).getWidth() > doc.getPage(0).getHeight());
await writeFile("/tmp/casepilot-receipt-sample.pdf", result);
await writeFile("/tmp/casepilot-receipt-edited.pdf", await buildReceipt(await readFile("assets/receipt-template.pdf"), { ...data, customerName: "TEST CUSTOMER", transfer: "10.25", totalOverride: "99.99", wordsOverride: "MANUAL WORDS", companyName: "TEST COMPANY" }));
await assert.rejects(buildReceipt(await readFile("assets/receipt-template.pdf"), { ...data, customerName: "Long Name ".repeat(100) }), /terlalu panjang/);
console.log("PASS: receipt amounts, words, overrides, filename, landscape and single-page PDF");
