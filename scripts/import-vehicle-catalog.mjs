import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

// Development-only HTML parser; no dependency is shipped to the application.
const { parseHTML } = await import(pathToFileURL(process.env.DOM_PARSER_PATH || "/tmp/casepilot-catalog-tools/node_modules/linkedom/esm/index.js").href);
const origin = "https://www.zigwheels.my";
async function documentFor(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30000) });
  if (!response.ok) throw new Error(`${url}: ${response.status}`);
  return parseHTML(await response.text()).document;
}
const root = await documentFor(`${origin}/new-cars`);
const brandUrls = [...new Set([...root.querySelectorAll('a[href]')].map(a => new URL(a.getAttribute('href'), origin).href).filter(url => /^https:\/\/www\.zigwheels\.my\/new-cars\/[^/]+$/.test(url)))];
const excluded = new Set(["dealers", "service-centers", "videos", "brochures"]);
const rows = [];
const failures = [];
for (const url of brandUrls) {
  const slug = url.split('/').at(-1);
  if (excluded.has(slug)) continue;
  try {
    const document = await documentFor(url);
    const brandSchema = [...document.querySelectorAll('script[type="application/ld+json"]')].map(s => {try { return JSON.parse(s.textContent); } catch { return null; }}).find(s => s?.['@type']?.toLowerCase() === 'brand');
    if (!brandSchema) continue;
    const brand = brandSchema.name;
    const models = [...document.querySelectorAll('a.vh-name')].filter(a => (a.getAttribute('onclick') || '').includes("pushDataLayer('new_car', 'click_name'"));
    for (const a of models) {
      const card = a.closest('li.filter-listing-card');
      const price = card?.querySelector('.vh-price')?.textContent || '';
      if (!/RM\s*[\d]/.test(price) || /expected|discontinued|coming soon/i.test(card?.textContent || '')) continue;
      const source = new URL(a.getAttribute('href'), origin).href;
      const modelSlug = source.split('/').at(-1);
      const variants = [...document.querySelectorAll('tr.model-change__variant')].filter(v => v.getAttribute('data-modelSlug') === modelSlug);
      if (!variants.length) { failures.push(source); continue; }
      const segment = variants[0].querySelectorAll('td')[2]?.textContent.trim().split(',')[0] || "";
      rows.push({ brand, model: a.textContent.trim(), segment, variants: [...new Set(variants.map(v => v.getAttribute('data-variantName').trim()))], colors: [], source });
    }
    console.log(`${brand}: ${models.length} models`);
    await new Promise(resolve => setTimeout(resolve, 150));
  } catch (error) { failures.push(`${url}: ${error.message}`); }
}
if (rows.length < 100) throw new Error(`Incomplete catalog: ${rows.length} models`);
rows.sort((a,b) => a.brand.localeCompare(b.brand) || a.model.localeCompare(b.model));
const unique = [...new Map(rows.map(row => [row.model, row])).values()];
await writeFile(new URL('../supabase/functions/_shared/vehicle-catalog.ts', import.meta.url), `// Generated by scripts/import-vehicle-catalog.mjs. New-car listings only.\nexport const vehicleCatalogCheckedAt = ${JSON.stringify(new Date().toISOString())};\nexport const vehicleCatalog = ${JSON.stringify(unique, null, 2)};\n`);
await writeFile(new URL('../scripts/vehicle-catalog-import-report.json', import.meta.url), JSON.stringify({ models: unique.length, brands: new Set(unique.map(r=>r.brand)).size, failures }, null, 2));
console.log(JSON.stringify({ models: unique.length, brands: new Set(unique.map(r=>r.brand)).size, failures }));
