import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
const url = text => `data:text/javascript;base64,${Buffer.from(text).toString("base64")}`;
const compile = source => ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
let source = compile(await readFile("src/lib/client-documents.ts", "utf8"));
for (const name of ["invoice", "receipt", "ehakmilik"]) source = source.replace(`from "@/lib/${name}"`, `from "${url(compile(await readFile(`src/lib/${name}.ts`, "utf8")))}"`);
source = source.replace('from "@/lib/honda-vso.mjs"', `from "${pathToFileURL(resolve("src/lib/honda-vso.mjs"))}"`).replace('from "@/lib/supabase"', `from "${url("export function getSupabaseClient(){throw new Error('No database in mapping test')} ")}"`);
const { blankBundle, newDraft, updateDocument, documentWithShared, normalizedClientPhone } = await import(url(source));
for (const phone of ["0173559147", "+60 17-355 9147", "60173559147", "173559147"]) assert.equal(normalizedClientPhone(phone), "60173559147");
assert.equal(normalizedClientPhone(""), "");
let bundle = blankBundle("owner");
bundle.client.data = { customerName: "Client", phone: "0173559147", email: "test@example.com", nric: "NRIC", address: "Address" };
bundle.purchase.data = { model: "City", variant: "V", chassisNo: "CHASSIS", engineNo: "ENGINE", colour: "Red", plate: "AAA1" };
for (const kind of ["invoice", "honda_vso", "receipt", "ehakmilik"]) bundle.documents.push(newDraft(kind, bundle.purchase.id, "Agent", "0123456789"));
const invoice = bundle.documents[0];
const filled = documentWithShared("invoice", invoice.data, bundle.client.data, bundle.purchase.data);
assert.equal(filled.chassis, "CHASSIS");
bundle = updateDocument(bundle, invoice, { ...filled, customerName: "Changed", payable: "999", colour: "Blue" });
assert.equal(bundle.client.data.email, "test@example.com");
assert.equal(bundle.client.data.phone, "0173559147");
const vso = documentWithShared("honda_vso", bundle.documents[1].data, bundle.client.data, bundle.purchase.data);
assert.equal(vso.customerName, "Changed"); assert.equal(vso.mobilePhone, "0173559147"); assert.equal(vso.engineNo, "ENGINE"); assert.equal(vso.colour, "Blue");
const receipt = documentWithShared("receipt", bundle.documents[2].data, bundle.client.data, bundle.purchase.data);
assert.equal(receipt.address, "Address"); assert.equal(receipt.chassisNo, "CHASSIS");
assert.equal(bundle.documents[0].data.payable, "999");
assert.equal(bundle.documents[2].data.transfer, "");
assert.notEqual(newDraft("receipt", bundle.purchase.id, "", "").id, newDraft("receipt", bundle.purchase.id, "", "").id);
console.log("PASS: Malaysia phone matching, shared fields, independent pricing, multiple receipt identities");

const ehak = documentWithShared("ehakmilik", bundle.documents[3].data, bundle.client.data, bundle.purchase.data);
assert.equal(ehak.nric, "NRIC"); assert.equal(ehak.customerName, "Changed"); assert.equal(ehak.variant, "V"); assert.equal(ehak.engineNo, "ENGINE");
const changedEhak = updateDocument(bundle, bundle.documents[3], { ...ehak, chassisNo: "NEW CHASSIS", bankName: "Test Bank" });
assert.equal(changedEhak.purchase.data.chassisNo, "NEW CHASSIS");
assert.equal(changedEhak.client.data.nric, "NRIC");
assert.equal(changedEhak.documents[0].data.payable, "999");
assert.equal(changedEhak.purchase.data.bankName, undefined);
console.log("PASS: e-hakmilik shared identity/vehicle fields and separate bank draft");
