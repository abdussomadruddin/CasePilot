import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import ts from "typescript";
import { PDFDocument } from "pdf-lib";
const source = await readFile("src/lib/ehakmilik.ts", "utf8");
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace('import("pdf-lib")', `import("${pathToFileURL(resolve("node_modules/pdf-lib/cjs/index.js"))}")`);
const { exampleEhakmilik, ehakmilikFilename, buildEhakmilik } = await import(`data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`);
const data = { ...exampleEhakmilik(), date: "2026-10-17" };
assert.equal(ehakmilikFilename(data), "e-hakmilik_PELANGGAN_CONTOH_2026-10-17.pdf");
const template = await readFile("assets/ehakmilik-template.pdf");
const bytes = await buildEhakmilik(template, data);
const pdf = await PDFDocument.load(bytes);
assert.equal(pdf.getPageCount(), 1);
assert.ok(Math.abs(pdf.getPage(0).getWidth() - 595.28) < 1);
assert.ok(pdf.getPage(0).getHeight() > pdf.getPage(0).getWidth());
await writeFile("/tmp/ehak-preview/sample.pdf", bytes);
await writeFile("/tmp/ehak-preview/long.pdf", await buildEhakmilik(template, { ...data, customerName: "NUR AIN BINTI ABDUL RAHMAN BIN MOHAMAD", model: "Honda City Hatchback", variant: "1.5L e:HEV RS", bankerName: "NAMA BANKER DENGAN NAMA PANJANG" }));
await assert.rejects(buildEhakmilik(template, { ...data, customerName: "Nama Panjang ".repeat(50) }), /terlalu panjang/);
console.log("PASS: e-hakmilik filename, portrait A4, single-page, long field limits and PDFs");
